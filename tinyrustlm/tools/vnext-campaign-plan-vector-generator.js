"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const {
  finalizeVnextCampaignPlan,
  validateCampaignPlanBytes
} = require("./vnext-campaign-projection.js");
const {
  canonicalizeVnextJcsBytes
} = require("./vnext-jcs.js");

const contractRoot = path.resolve(__dirname, "../../contracts/vnext");
const draftPath = path.join(contractRoot, "campaign-plan-draft-parity-fixture.v1.json");
const planPath = path.join(contractRoot, "campaign-plan-parity-fixture.v1.json");
const digest = (value) => crypto.createHash("sha256").update(value).digest("hex");

function modelSlot(index) {
  const ordinal = String(index + 1).padStart(2, "0");
  const artifactSha256 = digest(`campaign-artifact-${ordinal}`);
  return {
    artifactId: `sha256:${artifactSha256}`,
    artifactSha256,
    modelSlotId: `model-${ordinal}`,
    qualificationOperationId: `qualify-model-${ordinal}`
  };
}

function buildCampaignPlanDraft() {
  const models = Array.from({ length: 20 }, (_, index) => modelSlot(index));
  const browserRounds = Array.from({ length: 50 }, (_, index) => {
    const ordinal = String(index + 1).padStart(2, "0");
    const slot = models[index % models.length];
    return {
      memoryContinuityRequired: index < 25,
      modelSlotId: slot.modelSlotId,
      operationId: `browser-round-${ordinal}`,
      restartId: `restart-${ordinal}`,
      roundId: `round-${ordinal}`
    };
  });
  const memoryRounds = browserRounds.slice(0, 25).map((round, index) => {
    const ordinal = String(index + 1).padStart(2, "0");
    return {
      browserRoundId: round.roundId,
      companyIdHash: digest(`company-${ordinal}`),
      memoryRoundId: `memory-${ordinal}`,
      modelSlotId: round.modelSlotId,
      operationId: `memory-round-${ordinal}`
    };
  });
  const p2pLanes = models.flatMap((slot) => ["a", "b"].map((lane) => ({
    laneId: `${slot.modelSlotId}-lane-${lane}`,
    modelSlotId: slot.modelSlotId,
    processInstanceId: `${slot.modelSlotId}-process-${lane}`
  })));
  const announcements = models.map((slot) => ({
    announcementId: `announce-${slot.modelSlotId}`,
    modelSlotId: slot.modelSlotId,
    operationId: `announce-${slot.modelSlotId}`
  }));
  return {
    schema: "tinyrustlm.vnext.campaign_plan.v1",
    profileId: "tinyrustlm.vnext.campaign-projection.v1",
    campaignId: "campaign-vnext-001",
    environment: "production",
    applicationOrigin: "https://tinyrustlm.com",
    memoryContractId: `sha256:${digest("memory-contract-v1")}`,
    createdAtUtc: "2026-08-09T00:00:00Z",
    models,
    browserRounds,
    memoryRounds,
    p2pLanes,
    announcements
  };
}

function buildCampaignPlanVectorFiles() {
  const draft = buildCampaignPlanDraft();
  const draftBytes = canonicalizeVnextJcsBytes(draft, {
    maximumDepth: 32,
    maximumTotalEntries: 131072,
    maximumObjectMembers: 64,
    maximumArrayItems: 4096,
    maximumStringCodeUnits: 65536,
    maximumTotalStringCodeUnits: 16777216,
    numberProfile: "vnext-safe-integer"
  });
  const finalized = finalizeVnextCampaignPlan(draft);
  const validated = validateCampaignPlanBytes(finalized.bytes);
  if (!validated.bytes.equals(finalized.bytes)) {
    throw new Error("campaign plan validation changed generated bytes");
  }
  return Object.freeze({
    draftBytes,
    planBytes: finalized.bytes,
    planId: finalized.plan.planId,
    planSha256: finalized.planSha256
  });
}

if (require.main === module) {
  const vector = buildCampaignPlanVectorFiles();
  fs.writeFileSync(draftPath, vector.draftBytes, { flag: "w" });
  fs.writeFileSync(planPath, vector.planBytes, { flag: "w" });
}

module.exports = Object.freeze({
  buildCampaignPlanDraft,
  buildCampaignPlanVectorFiles,
  draftPath,
  planPath
});
